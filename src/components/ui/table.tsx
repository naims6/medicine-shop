/** Full-width empty / message row spanning all columns */
const TableEmpty = ({
  colSpan,
  children,
}: {
  colSpan: number;
  children: React.ReactNode;
}) => (
  <TableRow>
    <TableCell
      colSpan={colSpan}
      className="py-10 text-center text-xs text-slate-400"
    >
      {children}
    </TableCell>
  </TableRow>
);
TableEmpty.displayName = "TableEmpty";

export {
  Table,
  TableHeader,
  TableBody,
  TableRow,
  TableHead,
  TableCell,
  TableEmpty,
};
